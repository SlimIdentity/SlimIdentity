public sealed class EntityFrameworkStoreTests
{
    private static string SqliteFile() =>
        new SqliteConnectionStringBuilder
        {
            DataSource = Path.Combine(Path.GetTempPath(), $"slimidentity-ef-{Guid.NewGuid():N}.db"), DefaultTimeout = 30, Pooling = false,
        }.ToString();

    private static async Task<ServiceProvider> BuildAsync<TContext, TUser, TKey>(Action<DbContextOptionsBuilder> provider, bool wal = false)
        where TContext : DbContext
        where TUser : class, ISlimUserEntity<TKey>, new()
        where TKey : IEquatable<TKey>, IParsable<TKey>
    {
        var services = new ServiceCollection();
        services.AddDbContext<TContext>(provider);
        services.AddSingleton(TimeProvider.System);
        services.AddSlimIdentity(o => o.Tokens.JwtSecret = new string('x', 32)).AddEntityFrameworkStores<TContext, TUser, TKey>();
        var sp = services.BuildServiceProvider();
        await using var scope = sp.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<TContext>();
        await db.Database.EnsureDeletedAsync();
        await db.Database.EnsureCreatedAsync();
        if (wal) await db.Database.ExecuteSqlRawAsync("PRAGMA journal_mode=WAL;");
        return sp;
    }

    [Fact]
    public async Task Guid_keys_honour_all_store_contracts_on_SQLite()
    {
        var file = SqliteFile();   // once – the options callback runs per scope
        await using var sp = await BuildAsync<GuidContext, GuidUser, Guid>(o => o.UseSqlite(file), wal: true);
        var report = await SlimStoreConformance.VerifyAsync(sp);
        Assert.Equal(5, report.Results.Select(r => r.Store).Distinct().Count());
    }

    [Fact]
    public async Task Int_keys_honour_all_store_contracts_on_SQLite()
    {
        var file = SqliteFile();
        await using var sp = await BuildAsync<IntContext, IntUser, int>(o => o.UseSqlite(file), wal: true);
        await SlimStoreConformance.VerifyAsync(sp);
    }

    [SkippableFact]
    public async Task All_store_contracts_on_PostgreSQL()
    {
        var server = Environment.GetEnvironmentVariable("SLIMIDENTITY_TEST_POSTGRES");
        Skip.If(string.IsNullOrEmpty(server), "SLIMIDENTITY_TEST_POSTGRES is not set.");
        await using (var guid = await BuildAsync<GuidContext, GuidUser, Guid>(o => o.UseNpgsql(Database(server, "ef_package_guid"))))
            await SlimStoreConformance.VerifyAsync(guid);
        await using var integer = await BuildAsync<IntContext, IntUser, int>(o => o.UseNpgsql(Database(server, "ef_package_int")));
        await SlimStoreConformance.VerifyAsync(integer);

        static string Database(string server, string name) => new Npgsql.NpgsqlConnectionStringBuilder(server) { Database = name }.ToString();
    }

    [SkippableFact]
    public async Task All_store_contracts_on_SQL_Server()
    {
        var server = Environment.GetEnvironmentVariable("SLIMIDENTITY_TEST_SQLSERVER");
        Skip.If(string.IsNullOrEmpty(server), "SLIMIDENTITY_TEST_SQLSERVER is not set.");
        await using (var guid = await BuildAsync<GuidContext, GuidUser, Guid>(o => o.UseSqlServer(Database(server, "ef_package_guid"))))
            await SlimStoreConformance.VerifyAsync(guid);
        await using var integer = await BuildAsync<IntContext, IntUser, int>(o => o.UseSqlServer(Database(server, "ef_package_int")));
        await SlimStoreConformance.VerifyAsync(integer);

        static string Database(string server, string name) => new Microsoft.Data.SqlClient.SqlConnectionStringBuilder(server) { InitialCatalog = name }.ToString();
    }

    [Fact]
    public async Task Endpoints_work_end_to_end_with_claims_provider_and_user_factory()
    {
        var builder = WebApplication.CreateBuilder(new WebApplicationOptions { EnvironmentName = "Testing" });
        builder.WebHost.UseTestServer();
        builder.Logging.ClearProviders();
        var file = SqliteFile();
        builder.Services.AddDbContext<GuidContext>(o => o.UseSqlite(file));
        builder.Services.AddScoped<ISlimUserClaimsProvider<GuidUser>, RoleClaims>();
        builder.Services.AddSingleton<ISlimUserFactory<GuidUser>, NamedUsers>();
        builder.Services.AddSlimIdentity(o => o.Tokens.JwtSecret = new string('x', 32))
            .AddEntityFrameworkStores<GuidContext, GuidUser, Guid>()
            .AddNullEmailSender();

        await using var app = builder.Build();
        app.UseAuthentication();
        app.UseAuthorization();
        app.MapSlimIdentityApi();
        app.MapGet("/api/role", (ClaimsPrincipal u) => u.FindFirst(SlimClaimTypes.Role)?.Value).RequireAuthorization();
        await using (var scope = app.Services.CreateAsyncScope())
            await scope.ServiceProvider.GetRequiredService<GuidContext>().Database.EnsureCreatedAsync();
        await app.StartAsync();
        var http = app.GetTestClient();

        Assert.Equal(HttpStatusCode.OK, (await http.PostAsJsonAsync("/auth/register", new { email = "ef@test.local", password = "EfCore-Pass-123" })).StatusCode);
        var login = await http.PostAsJsonAsync("/auth/login", new { email = "EF@test.local", password = "EfCore-Pass-123" });
        Assert.Equal(HttpStatusCode.OK, login.StatusCode);
        var tokens = JsonDocument.Parse(await login.Content.ReadAsStringAsync()).RootElement;

        using var request = new HttpRequestMessage(HttpMethod.Get, "/api/role");
        request.Headers.Authorization = new("Bearer", tokens.GetProperty("accessToken").GetString());
        Assert.Equal("member", await (await http.SendAsync(request)).Content.ReadAsStringAsync());   // claims provider

        var refreshed = await http.PostAsJsonAsync("/auth/refresh", new { refreshToken = tokens.GetProperty("refreshToken").GetString() });
        Assert.Equal(HttpStatusCode.OK, refreshed.StatusCode);

        using var sessions = new HttpRequestMessage(HttpMethod.Get, "/auth/sessions");
        sessions.Headers.Authorization = new("Bearer", JsonDocument.Parse(await refreshed.Content.ReadAsStringAsync()).RootElement.GetProperty("accessToken").GetString());
        Assert.Equal(HttpStatusCode.OK, (await http.SendAsync(sessions)).StatusCode);

        await using var check = app.Services.CreateAsyncScope();
        var stored = await check.ServiceProvider.GetRequiredService<GuidContext>().Users.SingleAsync();
        Assert.Equal("new member", stored.DisplayName);   // user factory
        Assert.Equal("EF@TEST.LOCAL", stored.NormalizedEmail);
    }
}
