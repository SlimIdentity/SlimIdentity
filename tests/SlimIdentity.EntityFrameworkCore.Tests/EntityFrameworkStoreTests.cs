// ---------------------------------------------------------------------------------------------- test model

public class GuidUser : ISlimUserEntity<Guid>
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Email { get; set; } = "";
    public string NormalizedEmail { get; set; } = "";
    public string PasswordHash { get; set; } = "";
    public string SecurityStamp { get; set; } = "";
    public bool IsActive { get; set; } = true;
    public bool EmailConfirmed { get; set; }
    public int FailedLoginAttempts { get; set; }
    public DateTimeOffset? LockoutEndUtc { get; set; }
    public bool TwoFactorEnabled { get; set; }
    public bool PasswordChangeRequired { get; set; }
    public string? TotpSecret { get; set; }
    public long? LastTwoFactorCodeAt { get; set; }
    public long? LastTwoFactorChallengeAt { get; set; }

    public string Role { get; set; } = "member";         // business data of the host
    public string? DisplayName { get; set; }
}

public class IntUser : ISlimUserEntity<int>
{
    public int Id { get; set; }                         // generated by the database
    public string Email { get; set; } = "";
    public string NormalizedEmail { get; set; } = "";
    public string PasswordHash { get; set; } = "";
    public string SecurityStamp { get; set; } = "";
    public bool IsActive { get; set; } = true;
    public bool EmailConfirmed { get; set; }
    public int FailedLoginAttempts { get; set; }
    public DateTimeOffset? LockoutEndUtc { get; set; }
    public bool TwoFactorEnabled { get; set; }
    public bool PasswordChangeRequired { get; set; }
    public string? TotpSecret { get; set; }
    public long? LastTwoFactorCodeAt { get; set; }
    public long? LastTwoFactorChallengeAt { get; set; }
}

public sealed class GuidContext(DbContextOptions<GuidContext> options) : DbContext(options)
{
    public DbSet<GuidUser> Users => Set<GuidUser>();
    protected override void OnModelCreating(ModelBuilder b) => b.ApplySlimIdentity<GuidUser, Guid>();
}

public sealed class IntContext(DbContextOptions<IntContext> options) : DbContext(options)
{
    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<IntUser>().ToTable("Members");           // the host's own mapping stays in charge
        b.ApplySlimIdentity<IntUser, int>();
    }
}

public sealed class RoleClaims : ISlimUserClaimsProvider<GuidUser>
{
    public Task<IReadOnlyCollection<Claim>> GetClaimsAsync(GuidUser user, CancellationToken ct) =>
        Task.FromResult<IReadOnlyCollection<Claim>>([new Claim(ClaimTypes.Role, user.Role)]);
}

public sealed class NamedUsers : ISlimUserFactory<GuidUser>
{
    public GuidUser Create() => new() { DisplayName = "new member" };
}

