global using System.Globalization;
global using System.Security.Claims;
global using Microsoft.EntityFrameworkCore;
global using Microsoft.Extensions.DependencyInjection;

namespace SlimIdentity.EntityFrameworkCore;

/// <summary>
/// Implemented by <b>your</b> user entity – it keeps its own shape and business data; SlimIdentity only needs these
/// columns. Implement the members as ordinary public properties (not explicitly), so EF Core maps them as columns.
/// </summary>
/// <typeparam name="TKey">Key type of your users: <see cref="Guid"/>, <see cref="int"/>, <see cref="long"/> or <see cref="string"/>.</typeparam>
public interface ISlimUserEntity<TKey> where TKey : IEquatable<TKey>, IParsable<TKey>
{
    /// <summary>Primary key (generated by EF Core or the database when a user is created).</summary>
    TKey Id { get; }
    /// <summary>Login address as entered.</summary>
    string Email { get; set; }
    /// <summary>Upper-case address for the case-insensitive lookup; unique index.</summary>
    string NormalizedEmail { get; set; }
    /// <summary>PasswordHasher hash; empty for external-login and invited users.</summary>
    string PasswordHash { get; set; }
    /// <summary>Random value rotated on security events.</summary>
    string SecurityStamp { get; set; }
    /// <summary><c>false</c> = banned / deactivated.</summary>
    bool IsActive { get; set; }
    /// <summary>The address has been proven.</summary>
    bool EmailConfirmed { get; set; }
    /// <summary>Failed password attempts since the last success or reset.</summary>
    int FailedLoginAttempts { get; set; }
    /// <summary>End of the current password lockout.</summary>
    DateTimeOffset? LockoutEndUtc { get; set; }
    /// <summary>Failed second-factor attempts since the last success or reset.</summary>
    int FailedSecondFactorAttempts { get; set; }
    /// <summary>End of the current second-factor lockout.</summary>
    DateTimeOffset? SecondFactorLockoutEndUtc { get; set; }
    /// <summary>Second factor required.</summary>
    bool TwoFactorEnabled { get; set; }
    /// <summary>The password was set by an administrator and must be changed at the next sign-in.</summary>
    bool PasswordChangeRequired { get; set; }
    /// <summary>Authenticator secret, already encrypted by SlimIdentity (null = e-mail codes).</summary>
    string? TotpSecret { get; set; }
    /// <summary>Replay protection: unix milliseconds of the last accepted 2FA code.</summary>
    long? LastTwoFactorCodeAt { get; set; }
    /// <summary>Single-use sign-in challenges: unix milliseconds of the last completed challenge.</summary>
    long? LastTwoFactorChallengeAt { get; set; }
}

/// <summary>A refresh token (SHA-256 hash only). Table <c>SlimRefreshTokens</c>.</summary>
public sealed class SlimRefreshTokenEntity<TKey>
{
    /// <summary>SHA-256 hex of the token – primary key.</summary>
    public string TokenHash { get; set; } = string.Empty;
    /// <summary>Owner.</summary>
    public TKey UserId { get; set; } = default!;
    /// <summary>Expiry.</summary>
    public DateTimeOffset ExpiresAt { get; set; }
}

/// <summary>A server-side session. Table <c>SlimSessions</c>; delete rows with <c>ExpiresUtc</c> in the past periodically.</summary>
public sealed class SlimSessionEntity<TKey>
{
    /// <summary>Session id (32 hex characters) – primary key.</summary>
    public string Id { get; set; } = string.Empty;
    /// <summary>Owner.</summary>
    public TKey UserId { get; set; } = default!;
    /// <summary><c>cookie</c> or <c>bearer</c>.</summary>
    public string Mode { get; set; } = string.Empty;
    /// <summary><c>pwd</c>, <c>mfa</c>, <c>ext</c>, …</summary>
    public string AuthenticationMethod { get; set; } = string.Empty;
    /// <summary>Admin id for impersonation sessions.</summary>
    public string? ImpersonatorId { get; set; }
    /// <summary>Sign-in time.</summary>
    public DateTimeOffset CreatedUtc { get; set; }
    /// <summary>Last validation or refresh.</summary>
    public DateTimeOffset LastSeenUtc { get; set; }
    /// <summary>End of the session.</summary>
    public DateTimeOffset ExpiresUtc { get; set; }
    /// <summary>Personal data – set <see cref="SlimEntityFrameworkOptions.StoreClientInfo"/> to false to drop it.</summary>
    public string? UserAgent { get; set; }
    /// <summary>Personal data – set <see cref="SlimEntityFrameworkOptions.StoreClientInfo"/> to false to drop it.</summary>
    public string? IpAddress { get; set; }
}

/// <summary>A recovery code (hash only). Table <c>SlimRecoveryCodes</c>.</summary>
public sealed class SlimRecoveryCodeEntity<TKey>
{
    /// <summary>Owner.</summary>
    public TKey UserId { get; set; } = default!;
    /// <summary>Salted SHA-256 hex of the code.</summary>
    public string CodeHash { get; set; } = string.Empty;
}

/// <summary>A linked external identity. Table <c>SlimExternalLogins</c>.</summary>
public sealed class SlimExternalLoginEntity<TKey>
{
    /// <summary>Authentication scheme name, e.g. <c>Google</c>.</summary>
    public string Provider { get; set; } = string.Empty;
    /// <summary>Subject at the provider.</summary>
    public string ProviderKey { get; set; } = string.Empty;
    /// <summary>Linked user.</summary>
    public TKey UserId { get; set; } = default!;
}

/// <summary>A registered passkey (table <c>SlimPasskeys</c>).</summary>
public sealed class SlimPasskeyEntity<TKey>
{
    /// <summary>SHA-256 of the credential id – the key (credential ids may exceed index size limits).</summary>
    public byte[] CredentialIdHash { get; set; } = [];
    /// <summary>Credential id as chosen by the authenticator.</summary>
    public byte[] CredentialId { get; set; } = [];
    /// <summary>Owner.</summary>
    public TKey UserId { get; set; } = default!;
    /// <summary>COSE public key.</summary>
    public byte[] PublicKey { get; set; } = [];
    /// <summary>WebAuthn user handle (<c>null</c> for passkeys registered before it was stored).</summary>
    public byte[]? UserHandle { get; set; }
    /// <summary>Signature counter.</summary>
    public long SignCount { get; set; }
    /// <summary>May be synced to other devices (WebAuthn flag BE).</summary>
    public bool BackupEligible { get; set; }
    /// <summary>Currently synced (WebAuthn flag BS).</summary>
    public bool BackedUp { get; set; }
    /// <summary>Unix milliseconds of the last challenge used.</summary>
    public long? LastChallengeAt { get; set; }
    /// <summary>Display name.</summary>
    public string Name { get; set; } = string.Empty;
    /// <summary>Registration time.</summary>
    public DateTimeOffset CreatedUtc { get; set; }
    /// <summary>Last sign-in.</summary>
    public DateTimeOffset? LastUsedUtc { get; set; }
}

/// <summary>Model configuration: <c>modelBuilder.ApplySlimIdentity&lt;AppUser, Guid&gt;()</c> in <c>OnModelCreating</c>.</summary>
public static class SlimModelBuilderExtensions
{
    /// <summary>
    /// Configures the SlimIdentity columns of <typeparamref name="TUser"/> (lengths, unique index on
    /// <c>NormalizedEmail</c>) and adds the tables <c>SlimRefreshTokens</c>, <c>SlimSessions</c>, <c>SlimRecoveryCodes</c>,
    /// <c>SlimExternalLogins</c> and <c>SlimPasskeys</c> with a cascading foreign key to your users. Your own configuration of
    /// <typeparamref name="TUser"/> (table name, business columns) stays as it is.
    /// </summary>
    public static ModelBuilder ApplySlimIdentity<TUser, TKey>(this ModelBuilder modelBuilder)
        where TUser : class, ISlimUserEntity<TKey>
        where TKey : IEquatable<TKey>, IParsable<TKey>
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        modelBuilder.Entity<TUser>(e =>
        {
            e.HasKey(nameof(ISlimUserEntity<TKey>.Id));
            e.Property<string>(nameof(ISlimUserEntity<TKey>.Email)).HasMaxLength(256).IsRequired();
            e.Property<string>(nameof(ISlimUserEntity<TKey>.NormalizedEmail)).HasMaxLength(256).IsRequired();
            e.HasIndex(nameof(ISlimUserEntity<TKey>.NormalizedEmail)).IsUnique();
            e.Property<string>(nameof(ISlimUserEntity<TKey>.PasswordHash)).IsRequired();
            e.Property<string>(nameof(ISlimUserEntity<TKey>.SecurityStamp)).HasMaxLength(64).IsRequired();
        });

        modelBuilder.Entity<SlimRefreshTokenEntity<TKey>>(e =>
        {
            e.ToTable("SlimRefreshTokens");
            e.HasKey(x => x.TokenHash);
            e.Property(x => x.TokenHash).HasMaxLength(64);
            e.HasIndex(x => x.UserId);
            e.HasOne<TUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<SlimSessionEntity<TKey>>(e =>
        {
            e.ToTable("SlimSessions");
            e.HasKey(x => x.Id);
            e.Property(x => x.Id).HasMaxLength(32);
            e.Property(x => x.Mode).HasMaxLength(16);
            e.Property(x => x.AuthenticationMethod).HasMaxLength(32);
            e.Property(x => x.ImpersonatorId).HasMaxLength(256);
            e.Property(x => x.UserAgent).HasMaxLength(256);
            e.Property(x => x.IpAddress).HasMaxLength(64);
            e.HasIndex(x => x.UserId);
            e.HasIndex(x => x.ExpiresUtc);
            e.HasOne<TUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<SlimRecoveryCodeEntity<TKey>>(e =>
        {
            e.ToTable("SlimRecoveryCodes");
            e.HasKey(x => new { x.UserId, x.CodeHash });
            e.Property(x => x.CodeHash).HasMaxLength(64);
            e.HasOne<TUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<SlimExternalLoginEntity<TKey>>(e =>
        {
            e.ToTable("SlimExternalLogins");
            e.HasKey(x => new { x.Provider, x.ProviderKey });
            e.Property(x => x.Provider).HasMaxLength(128);
            e.Property(x => x.ProviderKey).HasMaxLength(256);
            e.HasIndex(x => x.UserId);
            e.HasOne<TUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<SlimPasskeyEntity<TKey>>(e =>
        {
            e.ToTable("SlimPasskeys");
            e.HasKey(x => x.CredentialIdHash);
            e.Property(x => x.CredentialIdHash).HasMaxLength(32);
            e.Property(x => x.CredentialId).HasMaxLength(1023);
            e.Property(x => x.PublicKey).HasMaxLength(1024);
            e.Property(x => x.UserHandle).HasMaxLength(64);
            e.Property(x => x.Name).HasMaxLength(64);
            e.HasIndex(x => x.UserId);
            e.HasOne<TUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        return modelBuilder;
    }
}
